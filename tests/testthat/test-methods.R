fit_small <- function() { x <- matrix(c(0, 2, 10, 12)); set.seed(1)
  list(x = x, fit = emeans(x, 2, centers = matrix(c(0, 10)), nepochs = 1, batch_size = 4, alpha0 = 0.5)) }
test_that("predict returns nearest labels and distances", {
  f <- fit_small()
  expect_identical(predict(f$fit, f$x), c(1L, 1L, 2L, 2L))
  expect_equal(predict(f$fit, f$x, type = "distance"), c(1, 1, 1, 1))
})
test_that("predict validates newdata and matches named columns", {
  set.seed(2); x <- matrix(rnorm(200), 100, 2, dimnames = list(NULL, c("a", "b"))); fit <- emeans(x, 3)
  expect_error(predict(fit, x[, 1, drop = FALSE]), class = "emeans_error_input")
  expect_error(predict(fit, rbind(x[1:2, ], c(NA, 1))), class = "emeans_error_input")
  expect_identical(predict(fit, as.data.frame(x)[, c("b", "a")]), predict(fit, x))
})
test_that("fitted mirrors kmeans and print/summary show the recipe", {
  f <- fit_small()
  expect_identical(fitted(f$fit, "classes"), f$fit$cluster)
  expect_equal(fitted(f$fit), f$fit$centers[f$fit$cluster, , drop = FALSE])
  out <- capture.output(print(f$fit))
  expect_true(any(grepl("batch 4", out))); expect_true(any(grepl("alpha0 0.5", out)))
  expect_true(any(grepl("tot.withinss", out)))
  expect_true(any(grepl("between_SS / total_SS", out)))
  bare <- capture.output(print(emeans(f$x, 2, nepochs = 1, keep_cluster = FALSE)))
  expect_true(any(grepl("last-pass objective", bare)))
  expect_s3_class(summary(f$fit), "summary.emeans")
})
test_that("spherical predict returns similarity", {
  set.seed(3); x <- matrix(rnorm(300), 100, 3); x <- x / sqrt(rowSums(x^2))
  fit <- emeans(x, 4, spherical = TRUE); s <- predict(fit, x, type = "distance")
  expect_true(all(s <= 1 + 1e-12 & s >= -1 - 1e-12))
})
test_that("fitted errors when labels were not kept and named columns must match", {
  set.seed(4); x <- matrix(rnorm(200), 100, 2, dimnames = list(NULL, c("a", "b")))
  fit <- emeans(x, 3, keep_cluster = FALSE)
  expect_error(fitted(fit), class = "emeans_error_input")
  fit2 <- emeans(x, 3)
  y <- x; colnames(y) <- c("a", "z")
  expect_error(predict(fit2, y), class = "emeans_error_input")
  expect_output(print(summary(fit2)), "size")
})
test_that("print works when the sizes exceed the integer range", {
  fit <- emeans(matrix(rnorm(40), 20), 2, nepochs = 1, threads = 1)
  fit$size <- c(2e9, 2e9)
  expect_output(print(fit), "4000000000 rows")
  bare <- emeans(matrix(rnorm(40), 20), 2, nepochs = 1, threads = 1,
                 keep_cluster = FALSE)
  expect_output(print(bare), "rows in the last pass")
  fit$size <- c(.Machine$integer.max, 5L)
  expect_output(print(fit), "2147483652")
})
